// add, subtract, divide, multiply, modulus, exponentiation, increment, decrement, assignment, comparison, logical, bitwise, ternary operators
let a = 10;
let b = 3;

console.log("Addition: " + (a + b));
console.log("Subtraction: " + (a - b));
console.log("Multiplication: " + (a * b));
console.log("Division: " + (a / b));
console.log("Modulus: " + (a % b));
console.log("Exponentiation: " + (a ** b));

console.log("Is Equal to: " + (a == b)); // >=, <=, !=, !==, >, <, >=, <=
console.log("Is Not Equal to: " + (a != b));
console.log("Is Greater than: " + (a > b));
console.log("Is Less than: " + (a < b));
console.log("Is Greater than or Equal to: " + (a >= b));
console.log("Is Less than or Equal to: " + (a <= b));